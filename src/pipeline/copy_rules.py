"""쇼츠 문장 다듬기 규칙 (BK 11/26 '문장을 다듬어야 될 것 같아 적용할 규칙을 정리해서 반영해줘').

11/26 삼촌 기름 편 제목 '기름은 언제 넣느냐, 어디서 넣느냐? 뭐가 더 클까?' — 옛말투('~느냐'), 무엇이 큰지 안 보이는
질문('뭐가 더 클까'), 주제와 따로 노는 격언체 자막('길을 안다고 믿는 건 늘 자신감부터다') 뒤에 넣음.
11/25 '향후에 문장을 완벽하게'(5락실 미용실 편)와 같은 방향. 사람이 읽을 기준은 docs/SHORTS_BANK.md 0장.

- SENTENCE_RULE: 대본·띠·제목을 쓰는 Claude 프롬프트에 넣는 규칙 글.
- copy_issues(text): 코드로 확실히 잡을 수 있는 것만 찾는다(옛말투 어미, 기준 없는 비교 질문, 격언체). 맞춤법은 ko_check.
"""
from __future__ import annotations

import re

SENTENCE_RULE = (
    "[문장 다듬기 — 모든 화면 글자·제목·설명 (BK 11/26 '문장을 다듬어야', 11/25 '문장을 완벽하게')]\n"
    "1. 처음 보는 사람 기준: 앞 장면을 안 봐도 그 한 줄만 읽고 뜻이 통해야 한다. 누가·무엇을이 빠진 문장 금지.\n"
    "2. 소리 내어 읽었을 때 자연스러운 요즘 말. 옛말투·문어체 어미 금지: '~느냐', '~는가', '~로다', '~노라', '~이니라'. "
    "번역투('~에 있어서', '~하는 것이 가능') 금지.\n"
    "3. 비교 질문은 무엇을 비교하는지 보이게: 'A vs B, [기준]은 어느 쪽이 더 ~?' 꼴. 기준 = 전기요금·기름값·가스비·물값·시간 같은 말"
    "(금액 숫자는 여전히 금지). '뭐가 더 클까?', '어디서가 더 클까?'처럼 기준 없는 질문 금지.\n"
    "   좋음) '기름값 차이, 넣는 날이 더 클까 주유소가 더 클까?', '가열식 vs 초음파 가습기, 한 달 전기요금 몇 배 차이?'\n"
    "   나쁨) '기름은 언제 넣느냐, 어디서 넣느냐? 뭐가 더 클까?'(옛말투 + 무엇이 큰지 없음), '끓이는 것 vs 쪼개는 것'(쪼갠다가 무슨 뜻인지 모름)\n"
    "4. A와 B는 같은 꼴로(명사 vs 명사, '~하기 vs ~하기'), 보는 사람이 아는 말로. 전문 용어를 풀어 쓴 엉뚱한 말·줄임말 금지.\n"
    "5. 한 편 안에서 띠 노란 줄 질문 = 유튜브 제목 질문 = 정답 컷의 답. 셋이 같은 것을 묻고 답한다(띠가 '언제·어디서'면 정답도 '어디서').\n"
    "6. 중간 자막(대사)은 동전이 장면을 따라가되 이 편 질문 주제와 이어진다. 주제와 상관없는 격언·명언투"
    "('~는 늘 ~부터다', '~하는 법이다', '~기 마련이다') 금지.\n"
    "7. 한 문장에 한 뜻. 같은 말·같은 어미를 한 문장에서 되풀이하지 않는다(대비용 'A vs B' 꼴은 괜찮음).\n"
    "8. 설명란 첫 줄은 이 편 질문을 한 문장으로 그대로(띠·제목과 같은 질문). 맞춤법·띄어쓰기는 올리기 전에 자동으로 고친다.\n"
)

# 11/27: '어디서 넣느냐가 더 크다'(11/26 설명란 첫 줄)처럼 뒤에 조사가 붙은 '~느냐가·~느냐는·~느냐에'도 잡는다
OLD_ENDING = re.compile(r"[가-힣](?:느냐|는가|로다|노라|이니라)(?=[\s,.?!…]|$|[가는에를도의](?=[\s,.?!…]|$))")
VAGUE_Q = re.compile(r"(?:뭐가|무엇이|어디서가|어느\s*쪽이)\s*더\s*(?:클|크|들|나올|셀|많을)까")
MEASURE = re.compile(r"요금|[값비](?=[\s,.?!]|$|은|는|이|가|을|를|도)|전기|가스|기름값|물값|난방|시간|칼로리|무게|횟수")
MAXIM = re.compile(r"늘\s*\S+부터다|하는\s*법이다|[가-힣]+기\s*마련이다|인\s*법이다")


def copy_issues(text: str) -> list[str]:
    """한 줄(제목·띠·자막)의 문장 문제. 줄마다 따로 부른다(기준 말은 같은 줄에 있어야 함)."""
    out = []
    t = " ".join((text or "").split())
    if not t:
        return out
    for m in OLD_ENDING.finditer(t):
        out.append(f"옛말투 '{m.group(0)[1:]}' → 요즘 말로")
    if "어디서가" in t:
        out.append("'어디서가' 어색 → '어디서 넣는 게', '주유소가' 처럼")
    v = VAGUE_Q.search(t)
    if v and not MEASURE.search(t[:v.start()] + t[v.end():]):
        out.append(f"'{v.group(0)}' 무엇이 큰지 없음 → 기준(전기요금·기름값·시간 등)을 같은 줄에")
    m = MAXIM.search(t)
    if m:
        out.append(f"격언투 '{m.group(0)}' → 이 편 장면·질문과 이어지는 말로")
    return out


def lines_issues(lines: list[str]) -> list[str]:
    """여러 줄을 각각 검사해 '줄: 문제' 목록으로."""
    return [f"{ln} — {p}" for ln in lines if isinstance(ln, str) for p in copy_issues(ln)]


def variant_issues(v: dict) -> list[str]:
    """동전이 대본 후보(claude_jobs.VARIANT)의 띠·제목·자막 문장 문제. 자막 2줄은 합쳐 한 문장으로 본다."""
    lines = [v.get("yt_title", ""), " ".join(x for x in (v.get("band_top", ""), v.get("band_accent", "")) if x)]
    lines += [(c.get("caption") or "").replace("/", " ") for c in v.get("cuts") or []]
    return lines_issues(lines)
